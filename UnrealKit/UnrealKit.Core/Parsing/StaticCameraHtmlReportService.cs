    private static void AppendDeviceInfo(StringBuilder sb, StaticCameraPerfDeviceInfo info)
    {
        sb.AppendLine("<div class=\"card\">");
        sb.AppendLine("<h2>Device Information</h2>");
        sb.AppendLine("<div class=\"info-grid\">");

        AppendInfoField(sb, "OS Platform", info.OsPlatform);
        AppendInfoField(sb, "Device Make", info.DeviceMake);
        AppendInfoField(sb, "GPU Vendor", info.GpuVendor);
        AppendInfoField(sb, "Vulkan Available", info.VulkanAvailable?.ToString());
        AppendInfoField(sb, "Vulkan Version", info.VulkanVersion);

        sb.AppendLine("</div>");
        sb.AppendLine("</div>");
    }

    private static void AppendInfoField(StringBuilder sb, string label, string? value)
    {
        if (value is null) return;
        sb.AppendLine("<div class=\"info-item\">");
        sb.AppendFormat("<span class=\"info-label\">{0}</span>", EscapeHtml(label));
        sb.AppendLine();
        sb.AppendFormat("<span class=\"info-value\">{0}</span>", EscapeHtml(value));
        sb.AppendLine();
        sb.AppendLine("</div>");
    }

    private static void AppendSummary(StringBuilder sb, StaticCameraPerfReport report, StaticCameraPerfConfig config, IReadOnlyList<Diagnostic> diagnostics)
    {
        sb.AppendLine("<div class=\"card\">");
        sb.AppendLine("<h2>Summary</h2>");

        sb.AppendLine("<div class=\"info-grid\" style=\"margin-bottom:20px\">");
        AppendInfoField(sb, "Camera Count", report.CameraCount.ToString());
        AppendInfoField(sb, "Parsed Cameras", report.ParseCameraCount.ToString());
        AppendInfoField(sb, "Completeness", report.Completeness.ToString());
        AppendInfoField(sb, "Diagnostics", diagnostics.Count.ToString());
        sb.AppendLine("</div>");

        sb.AppendLine("<table>");
        sb.AppendLine("<thead><tr>");
        sb.AppendLine("<th>Metric</th><th>Average</th><th>Warning</th><th>Error</th><th>Status</th>");
        sb.AppendLine("</tr></thead><tbody>");

        AppendMetricRow(sb, "Frame Time", report.Average.FrameTimeMs, "ms", config.FrameTimeWarningMs, config.FrameTimeErrorMs, higherIsWorse: true);
        AppendMetricRow(sb, "Game Time", report.Average.GameTimeMs, "ms", null, null, null);
        AppendMetricRow(sb, "Draw Time", report.Average.DrawTimeMs, "ms", null, null, null);
        AppendMetricRow(sb, "RHI Time", report.Average.RhiTimeMs, "ms", null, null, null);
        AppendMetricRow(sb, "GPU Time", report.Average.GpuTimeMs, "ms", null, null, null);
        AppendMetricRow(sb, "Memory", report.Average.MemoryBytes, "bytes", null, null, null);
        AppendMetricRow(sb, "Draw Calls", report.Average.DrawCalls, "", config.DrawCallWarning, config.DrawCallError, higherIsWorse: true);
        AppendMetricRow(sb, "Triangles", report.Average.Triangles, "", config.TriangleWarning, config.TriangleError, higherIsWorse: true);

        sb.AppendLine("</tbody></table>");
        sb.AppendLine("</div>");
    }

    private static void AppendMetricRow(StringBuilder sb, string name, double value, string unit, double? warningThreshold, double? errorThreshold, bool? higherIsWorse)
    {
        var (status, cssClass) = GetThresholdStatus(value, warningThreshold, errorThreshold, higherIsWorse ?? false);
        sb.AppendLine("<tr>");
        sb.AppendFormat("<td>{0}</td>", EscapeHtml(name));
        sb.AppendLine();
        sb.AppendFormat("<td class=\"{0}\">{1} {2}</td>", cssClass, value.ToString("F2", CultureInfo.InvariantCulture), EscapeHtml(unit));
        sb.AppendLine();
        sb.AppendFormat("<td>{0}</td>", warningThreshold?.ToString(CultureInfo.InvariantCulture) ?? "-");
        sb.AppendLine();
        sb.AppendFormat("<td>{0}</td>", errorThreshold?.ToString(CultureInfo.InvariantCulture) ?? "-");
        sb.AppendLine();
        sb.AppendFormat("<td class=\"{0}\">{1}</td>", cssClass, status);
        sb.AppendLine();
        sb.AppendLine("</tr>");
    }

    private static void AppendMetricRow(StringBuilder sb, string name, long value, string unit, long? warningThreshold, long? errorThreshold, bool? higherIsWorse)
    {
        var (status, cssClass) = GetThresholdStatus(value, warningThreshold, errorThreshold, higherIsWorse ?? false);
        sb.AppendLine("<tr>");
        sb.AppendFormat("<td>{0}</td>", EscapeHtml(name));
        sb.AppendLine();
        sb.AppendFormat("<td class=\"{0}\">{1} {2}</td>", cssClass, value.ToString(CultureInfo.InvariantCulture), EscapeHtml(unit));
        sb.AppendLine();
        sb.AppendFormat("<td>{0}</td>", warningThreshold?.ToString(CultureInfo.InvariantCulture) ?? "-");
        sb.AppendLine();
        sb.AppendFormat("<td>{0}</td>", errorThreshold?.ToString(CultureInfo.InvariantCulture) ?? "-");
        sb.AppendLine();
        sb.AppendFormat("<td class=\"{0}\">{1}</td>", cssClass, status);
        sb.AppendLine();
        sb.AppendLine("</tr>");
    }

    private static (string Status, string CssClass) GetThresholdStatus(double value, double? warning, double? error, bool higherIsWorse)
    {
        if (error.HasValue && (higherIsWorse ? value >= error.Value : value <= error.Value))
            return ("ERROR", "threshold-error");
        if (warning.HasValue && (higherIsWorse ? value >= warning.Value : value <= warning.Value))
            return ("WARNING", "threshold-warn");
        return ("OK", "threshold-ok");
    }

    private static (string Status, string CssClass) GetThresholdStatus(long value, long? warning, long? error, bool higherIsWorse)
    {
        if (error.HasValue && (higherIsWorse ? value >= error.Value : value <= error.Value))
            return ("ERROR", "threshold-error");
        if (warning.HasValue && (higherIsWorse ? value >= warning.Value : value <= warning.Value))
            return ("WARNING", "threshold-warn");
        return ("OK", "threshold-ok");
    }

    private static void AppendCameraDetails(StringBuilder sb, StaticCameraPerfReport report, StaticCameraPerfConfig config, string outputDir)
    {
        sb.AppendLine("<div class=\"card\">");
        sb.AppendLine("<h2>Camera Details</h2>");

        for (var i = 0; i < report.Frames.Count; i++)
        {
            AppendCameraCard(sb, report.Frames[i], config, outputDir, i);
        }

        sb.AppendLine("</div>");
    }

    private static void AppendCameraCard(StringBuilder sb, StaticCameraPerfFrame frame, StaticCameraPerfConfig config, string outputDir, int index)
    {
        var ftStatus = GetThresholdStatus(frame.FrameTimeMs, config.FrameTimeWarningMs, config.FrameTimeErrorMs, higherIsWorse: true);
        var dcStatus = GetThresholdStatus(frame.DrawCalls, config.DrawCallWarning, config.DrawCallError, higherIsWorse: true);
        var primStatus = GetThresholdStatus(frame.Triangles, config.TriangleWarning, config.TriangleError, higherIsWorse: true);

        var worstStatus = "OK";
        var worstCss = "badge-ok";
        if (ftStatus.Status == "ERROR" || dcStatus.Status == "ERROR" || primStatus.Status == "ERROR")
        { worstStatus = "ERROR"; worstCss = "badge-error"; }
        else if (ftStatus.Status == "WARNING" || dcStatus.Status == "WARNING" || primStatus.Status == "WARNING")
        { worstStatus = "WARNING"; worstCss = "badge-warn"; }

        var cameraId = $"camera-{index}";

        sb.AppendLine("<div style=\"border:1px solid #e2e6ea; border-radius:6px; padding:16px; margin-bottom:16px\">");
        sb.AppendFormat("<div class=\"camera-header\">");
        sb.AppendLine();
        sb.AppendFormat("<span class=\"collapsible-toggle open\" onclick=\"toggleCollapsible('{0}')\">", cameraId);
        sb.AppendFormat("<span class=\"camera-name\">{0} (#{1})</span>", EscapeHtml(frame.CameraName), frame.Index);
        sb.AppendLine("</span>");
        sb.AppendFormat("<span class=\"camera-badge {0}\">{1}</span>", worstCss, worstStatus);
        sb.AppendLine("</div>");

        sb.AppendFormat("<div id=\"{0}\" class=\"collapsible-content\">", cameraId);
        sb.AppendLine();

        sb.AppendLine("<table>");
        sb.AppendLine("<thead><tr><th>Metric</th><th>Value</th><th>Threshold</th><th>Status</th></tr></thead><tbody>");

        AppendFrameMetricRow(sb, "Frame Time", frame.FrameTimeMs, "ms", config.FrameTimeWarningMs, config.FrameTimeErrorMs, higherIsWorse: true);
        AppendFrameMetricRow(sb, "Game Time", frame.GameTimeMs, "ms", null, null, null);
        AppendFrameMetricRow(sb, "Draw Time", frame.DrawTimeMs, "ms", null, null, null);
        AppendFrameMetricRow(sb, "RHI Time", frame.RhiTimeMs, "ms", null, null, null);
        AppendFrameMetricRow(sb, "GPU Time", frame.GpuTimeMs, "ms", null, null, null);
        AppendFrameMetricRow(sb, "Memory", frame.MemoryBytes, "bytes", null, null, null);
        AppendFrameMetricRow(sb, "Draw Calls", frame.DrawCalls, "", config.DrawCallWarning, config.DrawCallError, higherIsWorse: true);
        AppendFrameMetricRow(sb, "Triangles", frame.Triangles, "", config.TriangleWarning, config.TriangleError, higherIsWorse: true);

        sb.AppendLine("</tbody></table>");

        if (frame.Screenshots.Count > 0)
        {
            sb.AppendFormat("<p style=\"margin-top:12px;font-weight:600;font-size:14px\">Screenshots ({0})</p>", frame.Screenshots.Count);
            sb.AppendLine();
            sb.AppendLine("<div class=\"screenshots\">");
            foreach (var screenshot in frame.Screenshots)
            {
                var relativePath = GetRelativePath(outputDir, screenshot);
                sb.AppendLine("<div class=\"screenshot-card\">");
                sb.AppendFormat("<img src=\"{0}\" alt=\"{1}\" loading=\"lazy\" />", EscapeHtml(relativePath), EscapeHtml(Path.GetFileName(screenshot)));
                sb.AppendLine();
                sb.AppendFormat("<div class=\"caption\">{0}</div>", EscapeHtml(Path.GetFileName(screenshot)));
                sb.AppendLine();
                sb.AppendLine("</div>");
            }
            sb.AppendLine("</div>");
        }

        sb.AppendLine("</div>");
        sb.AppendLine("</div>");
    }

    private static void AppendFrameMetricRow(StringBuilder sb, string name, double value, string unit, double? warningThreshold, double? errorThreshold, bool? higherIsWorse)
    {
        var (status, cssClass) = GetThresholdStatus(value, warningThreshold, errorThreshold, higherIsWorse ?? false);
        sb.AppendLine("<tr>");
        sb.AppendFormat("<td>{0}</td>", EscapeHtml(name));
        sb.AppendLine();
        sb.AppendFormat("<td class=\"{0}\">{1} {2}</td>", cssClass, value.ToString("F2", CultureInfo.InvariantCulture), EscapeHtml(unit));
        sb.AppendLine();
        if (warningThreshold.HasValue && errorThreshold.HasValue)
            sb.AppendFormat("<td>Warn: {0} / Error: {1}</td>", warningThreshold.Value.ToString(CultureInfo.InvariantCulture), errorThreshold.Value.ToString(CultureInfo.InvariantCulture));
        else
            sb.AppendLine("<td>-</td>");
        sb.AppendLine();
        sb.AppendFormat("<td class=\"{0}\">{1}</td>", cssClass, status);
        sb.AppendLine();
        sb.AppendLine("</tr>");
    }

    private static void AppendFrameMetricRow(StringBuilder sb, string name, long value, string unit, long? warningThreshold, long? errorThreshold, bool? higherIsWorse)
    {
        var (status, cssClass) = GetThresholdStatus(value, warningThreshold, errorThreshold, higherIsWorse ?? false);
        sb.AppendLine("<tr>");
        sb.AppendFormat("<td>{0}</td>", EscapeHtml(name));
        sb.AppendLine();
        sb.AppendFormat("<td class=\"{0}\">{1} {2}</td>", cssClass, value.ToString(CultureInfo.InvariantCulture), EscapeHtml(unit));
        sb.AppendLine();
        if (warningThreshold.HasValue && errorThreshold.HasValue)
            sb.AppendFormat("<td>Warn: {0} / Error: {1}</td>", warningThreshold.Value.ToString(CultureInfo.InvariantCulture), errorThreshold.Value.ToString(CultureInfo.InvariantCulture));
        else
            sb.AppendLine("<td>-</td>");
        sb.AppendLine();
        sb.AppendFormat("<td class=\"{0}\">{1}</td>", cssClass, status);
        sb.AppendLine();
        sb.AppendLine("</tr>");
    }

    private static void AppendDiagnostics(StringBuilder sb, IReadOnlyList<Diagnostic> diagnostics)
    {
        if (diagnostics.Count == 0) return;

        sb.AppendLine("<div class=\"card\">");
        sb.AppendLine("<h2>Diagnostics</h2>");
        sb.AppendLine("<ul class=\"diag-list\">");

        foreach (var diag in diagnostics.OrderByDescending(d => d.Severity))
        {
            var cssClass = diag.Severity == DiagnosticSeverity.Error ? "diag-error" : "diag-warn";
            var location = diag.LineNumber.HasValue
                ? $"{Path.GetFileName(diag.Path)}:{diag.LineNumber.Value}"
                : Path.GetFileName(diag.Path);

            sb.AppendFormat("<li class=\"diag-item {0}\">", cssClass);
            sb.AppendLine();
            sb.AppendFormat("<span class=\"diag-code\">{0}</span>", EscapeHtml(diag.Code));
            sb.AppendFormat("<span class=\"diag-msg\">{0}", EscapeHtml(diag.Message));
            if (!string.IsNullOrWhiteSpace(diag.SuggestedFix))
                sb.AppendFormat(" <em>({0})</em>", EscapeHtml(diag.SuggestedFix));
            sb.AppendLine("</span>");
            sb.AppendFormat("<span class=\"diag-location\">{0}</span>", EscapeHtml(location));
            sb.AppendLine();
            sb.AppendLine("</li>");
        }

        sb.AppendLine("</ul>");
        sb.AppendLine("</div>");
    }

    private static string GetRelativePath(string baseDir, string targetPath)
    {
        var baseUri = new Uri(baseDir.EndsWith(Path.DirectorySeparatorChar.ToString()) ? baseDir : baseDir + Path.DirectorySeparatorChar);
        var targetUri = new Uri(targetPath);
        return Uri.UnescapeDataString(baseUri.MakeRelativeUri(targetUri).ToString().Replace('/', Path.DirectorySeparatorChar));
    }

    private static string EscapeHtml(string? value)
    {
        if (value is null) return string.Empty;
        return System.Net.WebUtility.HtmlEncode(value);
    }
