    public async Task<StaticCameraHtmlReportResult> GenerateAsync(
        StaticCameraHtmlReportRequest request,
        CancellationToken cancellationToken = default)
    {
        ArgumentNullException.ThrowIfNull(request);
        ArgumentException.ThrowIfNullOrWhiteSpace(request.OutputFilePath);
        ArgumentNullException.ThrowIfNull(request.ParseResult);

        var config = request.Config ?? StaticCameraPerfConfig.Default;
        config.Validate();

        var outputPath = Path.GetFullPath(request.OutputFilePath);
        var outputDir = Path.GetDirectoryName(outputPath);
        if (!string.IsNullOrWhiteSpace(outputDir))
            Directory.CreateDirectory(outputDir);

        var html = BuildHtml(request.ParseResult, config, outputDir!);
        await File.WriteAllTextAsync(outputPath, html, new UTF8Encoding(encoderShouldEmitUTF8Identifier: false), cancellationToken);

        return new StaticCameraHtmlReportResult(outputPath);
    }

    private static string BuildHtml(StaticCameraPerfParseResult result, StaticCameraPerfConfig config, string outputDir)
    {
        var sb = new StringBuilder();
        var report = result.Report;

        sb.AppendLine("<!DOCTYPE html>");
        sb.AppendLine("<html lang=\"zh-CN\">");
        sb.AppendLine("<head>");
        sb.AppendLine("<meta charset=\"UTF-8\">");
        sb.AppendLine("<meta name=\"viewport\" content=\"width=device-width, initial-scale=1.0\">");
        sb.AppendLine("<title>Static Camera Performance Report</title>");
        AppendStyles(sb);
        AppendScript(sb);
        sb.AppendLine("</head>");
        sb.AppendLine("<body>");
        sb.AppendLine("<div class=\"container\">");

        sb.AppendLine("<header>");
        sb.AppendLine("<h1>&#x1F4F7; Static Camera Performance Report</h1>");
        sb.AppendFormat("<p class=\"subtitle\">Source: {0}</p>", EscapeHtml(result.InputPath));
        sb.AppendLine();
        sb.AppendLine("</header>");

        if (report is not null)
        {
            AppendDeviceInfo(sb, report.DeviceInfo);
            AppendSummary(sb, report, config, result.Diagnostics);
            AppendCameraDetails(sb, report, config, outputDir);
        }

        AppendDiagnostics(sb, result.Diagnostics);

        sb.AppendLine("<div class=\"footer\">Generated by UnrealKit</div>");
        sb.AppendLine("</div>");
        sb.AppendLine("</body>");
        sb.AppendLine("</html>");

        return sb.ToString();
    }

    private static void AppendScript(StringBuilder sb)
    {
        sb.AppendLine("<script>");
        sb.AppendLine("function toggleCollapsible(id) {");
        sb.AppendLine("  var el = document.getElementById(id);");
        sb.AppendLine("  if (!el) return;");
        sb.AppendLine("  el.classList.toggle('collapsed');");
        sb.AppendLine("  var toggle = el.previousElementSibling;");
        sb.AppendLine("  if (toggle) toggle.classList.toggle('open');");
        sb.AppendLine("}");
        sb.AppendLine("</script>");
    }

